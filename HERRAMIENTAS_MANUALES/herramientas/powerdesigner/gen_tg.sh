#!/usr/bin/env bash
# Genera el espacio de trabajo de casos de uso de un TG en PowerDesigner 16.1:
#   <TG>/<espacio>.sws, 01_CASOS_USO.prj, diagrama general (casos críticos) y 7 diagramas detallados (.oom + .png).
# uso: bash gen_tg.sh <carpeta_TG> <nombre_sws_sin_ext> <modelo_general> <titulo_general> <sufijo_detalle>
set -u
S="$(cd "$(dirname "$0")" && pwd)"
RAIZ="$(cd "$S/../../.." && pwd)"
TPL="$RAIZ/TI.1.1. PAO202651_SOAP_JAVA_SINBDD_NRC36884_GR03/01. UML/03 DIAGRAMAS/01_CASOS_USO"
TMP="$S/tmp"; mkdir -p "$TMP"
TG="$1"; SWS="$2"; GEN="$3"; TIT="$4"; SUF="$5"
D="$TG/01. UML/03 DIAGRAMAS/01_CASOS_USO"; mkdir -p "$D"
LEEME="$TG/01. UML/03 DIAGRAMAS/README.txt"; [ -f "$LEEME" ] && [ ! -s "$LEEME" ] && rm -f "${LEEME:?}"

# PowerDesigner tarda en cerrarse; si se lanza otra ejecución antes, falla con "Error catastrófico"
esperar(){ for k in $(seq 1 90); do tasklist | grep -qi pdshell || { sleep 4; return 0; }; sleep 2; done; echo "PowerDesigner sigue abierto"; }
w(){ cygpath -w "$1"; }
CSCRIPT=C:/Windows/SysWOW64/cscript.exe   # PowerDesigner 16 es de 32 bits

generar(){ # vbs spec|- modelo nombre_diagrama titulo
  local vbs="$1" spec="$2" a="$3" diag="$4" t="$5"
  for intento in 1 2 3; do
    esperar; cp "$TPL/CU_Realizar_Conversion.oom" "$TMP/base.oom"; rm -f "${D:?}/${a:?}.oom"
    if [ "$spec" = "-" ]; then
      "$CSCRIPT" //nologo "$(w "$S/$vbs")" "$(w "$TMP/base.oom")" "$(w "$D/$a.oom")" "$(w "$TMP/x.png")" "x" "$a" >/dev/null 2>&1
    else
      "$CSCRIPT" //nologo "$(w "$S/$vbs")" "$(w "$TMP/base.oom")" "$(w "$D/$a.oom")" "x" "$(w "$S/specs/$spec")" "$a" "$diag" >/dev/null 2>&1
    fi
    [ -f "$D/$a.oom" ] && [ "$(stat -c %s "$D/$a.oom")" -gt 20000 ] && break
  done
  python -I "$S/finalizar_oom.py" "$D/$a.oom" "$TMP/base.oom" "$t" >/dev/null || echo "fallo al finalizar $a"
  for intento in 1 2 3; do esperar; "$CSCRIPT" //nologo "$(w "$S/exportar.vbs")" "$(w "$D/$a.oom")" "$(w "$D/$a.png")" >/dev/null 2>&1; [ -f "$D/$a.png" ] && break; done
  echo "  $a oom=$(stat -c %s "$D/$a.oom") png=$([ -f "$D/$a.png" ] && echo ok || echo FALTA)"
}

echo "== $SWS"
generar cu_criticos.vbs - "$GEN" "" "$TIT"
declare -A ARCH=([1]=CU_Iniciar_Sesion [2]=CU_Cerrar_Sesion [3]=CU_Consultar_Cuenta [4]=CU_Consultar_Movimientos [5]=CU_Registrar_Deposito [6]=CU_Registrar_Retiro [7]=CU_Registrar_Transferencia)
declare -A NOM=([1]="Iniciar sesión" [2]="Cerrar sesión" [3]="Consultar cuenta" [4]="Consultar movimientos" [5]="Registrar depósito" [6]="Registrar retiro" [7]="Registrar transferencia")
declare -A MAY=([1]="INICIAR SESIÓN" [2]="CERRAR SESIÓN" [3]="CONSULTAR CUENTA" [4]="CONSULTAR MOVIMIENTOS" [5]="REGISTRAR DEPÓSITO" [6]="REGISTRAR RETIRO" [7]="REGISTRAR TRANSFERENCIA")
modelos=("$D/$GEN.oom")
for n in 1 2 3 4 5 6 7; do
  generar cu_detalle.vbs "spec_$n.txt" "${ARCH[$n]}" "Caso de uso ${NOM[$n]}" "ECUD$n: ${MAY[$n]} – $SUF"
  modelos+=("$D/${ARCH[$n]}.oom")
done
PID=$(python -I "$S/crear_prj.py" "$TPL/01_CASOS_USO.prj" "$D/01_CASOS_USO.prj" "01_CASOS_USO" "${modelos[@]}")
printf '<?xml version="1.0" encoding="UTF-8"?>\r\n<?PowerDesigner signature="Workspace" version="16.1.0.3637"?>\r\n<!-- do not edit this file -->\r\n\r\n<Workspace>\r\n\t<Local Expanded="Yes" Name="%s">\r\n\t\t<Model Expanded="Yes" ID="{%s}" Name="01_CASOS_USO" Selected="Yes" Type="{FF4B6538-9856-42CF-B9B9-304ED370CEAA}" URL="01. UML/03 DIAGRAMAS/01_CASOS_USO/01_CASOS_USO.prj"/>\r\n\t</Local>\r\n\t<BrowserModule Name="Repository"/>\r\n</Workspace>\r\n' "$SWS" "$PID" > "$TG/$SWS.sws"
esperar
"$CSCRIPT" //nologo "$(w "$S/verificar_prj.vbs")" "$(w "$D/01_CASOS_USO.prj")" "$(w "$TG/$SWS.sws")" 2>&1 | grep -E "Documentos|Workspace"
