#!/usr/bin/env bash
# Casos de uso de un proyecto a partir de specs/casos_uso/<clave>/*.txt (UTF-8, primera línea '#|modelo|diagrama|título'):
#   <carpeta>/01. UML/03 DIAGRAMAS/01_CASOS_USO/<modelo>.oom (sin PNG; la imagen de revisión queda en tmp/revision),
#   01_CASOS_USO.prj y su entrada en <espacio>.sws (el .sws se crea si no existe).
# uso: bash gen_cu_specs.sh <carpeta_proyecto> <espacio_sws_sin_ext> <clave_specs> [modelo ...]
#   con modelos, solo se regeneran esos; el .prj siempre incluye todos los specs de la clave.
set -u
S="$(cd "$(dirname "$0")" && pwd)"
RAIZ="$(cd "$S/../../.." && pwd)"
TPL="$RAIZ/TI.1.1. PAO202651_SOAP_JAVA_SINBDD_NRC36884_GR03/01. UML/03 DIAGRAMAS/01_CASOS_USO"
TMP="$S/tmp"; REV="$TMP/revision"; mkdir -p "$REV"
TG="$(cd "$1" && pwd)"; SWS="$2"; CLAVE="$3"; shift 3; solo=" $* "
D="$TG/01. UML/03 DIAGRAMAS/01_CASOS_USO"; mkdir -p "$D"
esperar(){ for k in $(seq 1 90); do tasklist | grep -qi pdshell || { sleep 4; return 0; }; sleep 2; done; echo "PowerDesigner sigue abierto"; }
w(){ cygpath -w "$1"; }
CSCRIPT=C:/Windows/SysWOW64/cscript.exe   # PowerDesigner 16 es de 32 bits

modelos=()
for spec in "$S/specs/casos_uso/$CLAVE"/*.txt; do
  IFS='|' read -r _ a diag titulo < "$spec"
  modelos+=("$D/$a.oom")
  [ "$solo" != "  " ] && [[ "$solo" != *" $a "* ]] && continue
  iconv -f UTF-8 -t UTF-16LE "$spec" | { printf '\xff\xfe'; cat; } > "$TMP/spec_cu.txt"
  for intento in 1 2 3; do
    esperar; cp "$TPL/CU_Realizar_Conversion.oom" "$TMP/base_cu.oom"; rm -f "${D:?}/${a:?}.oom"
    "$CSCRIPT" //nologo "$(w "$S/cu_detalle.vbs")" "$(w "$TMP/base_cu.oom")" "$(w "$D/$a.oom")" "x" "$(w "$TMP/spec_cu.txt")" "$a" "$diag" >/dev/null 2>&1
    [ -f "$D/$a.oom" ] && [ "$(stat -c %s "$D/$a.oom")" -gt 20000 ] && break
  done
  python -I "$S/finalizar_cu.py" "$D/$a.oom" "$TMP/base_cu.oom" "$spec" "$titulo" >/dev/null || echo "fallo al finalizar $a"
  rm -f "${REV:?}/${a:?}.png"
  for intento in 1 2 3; do esperar; "$CSCRIPT" //nologo "$(w "$S/exportar.vbs")" "$(w "$D/$a.oom")" "$(w "$REV/$a.png")" >/dev/null 2>&1; [ -f "$REV/$a.png" ] && break; done
  echo "  $a oom=$(stat -c %s "$D/$a.oom") revision=$([ -f "$REV/$a.png" ] && echo ok || echo FALTA)"
done
PID=$(python -I "$S/crear_prj.py" "$TPL/01_CASOS_USO.prj" "$D/01_CASOS_USO.prj" "01_CASOS_USO" "${modelos[@]}")
[ -f "$TG/$SWS.sws" ] || printf '<?xml version="1.0" encoding="UTF-8"?>\r\n<?PowerDesigner signature="Workspace" version="16.1.0.3637"?>\r\n<!-- do not edit this file -->\r\n\r\n<Workspace>\r\n\t<Local Expanded="Yes" Name="%s">\r\n\t</Local>\r\n\t<BrowserModule Name="Repository"/>\r\n</Workspace>\r\n' "$SWS" > "$TG/$SWS.sws"
python -I "$S/agregar_sws.py" "$TG/$SWS.sws" 01_CASOS_USO "$PID" "01. UML/03 DIAGRAMAS/01_CASOS_USO/01_CASOS_USO.prj" >/dev/null
esperar
"$CSCRIPT" //nologo "$(w "$S/verificar_prj.vbs")" "$(w "$D/01_CASOS_USO.prj")" "$(w "$TG/$SWS.sws")" 2>&1 | iconv -f CP850 -t UTF-8 | grep -vE "^ - "
